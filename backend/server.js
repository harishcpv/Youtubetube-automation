const express = require('express');
const cors = require('cors');
const path = require('path');
const fs = require('fs');
const archiver = require('archiver');
require('dotenv').config();

const app = express();
const PORT = process.env.PORT || 5000;

// Middleware
app.use(cors());
app.use(express.json({ limit: '50mb' }));
app.use(express.urlencoded({ extended: true, limit: '50mb' }));

// Static file serving
const uploadsDir = path.join(__dirname, '../uploads');
const outputsDir = path.join(__dirname, '../outputs');
const clientDist = path.join(__dirname, '../client/dist');

if (!fs.existsSync(uploadsDir)) fs.mkdirSync(uploadsDir, { recursive: true });
if (!fs.existsSync(outputsDir)) fs.mkdirSync(outputsDir, { recursive: true });

app.use('/uploads', express.static(uploadsDir));
app.use('/outputs', express.static(outputsDir));

// Routes
const videoRoutes = require('./routes/video');
const policyRoutes = require('./routes/policy');
const thumbnailRoutes = require('./routes/thumbnail');
const seoRoutes = require('./routes/seo');
const autopilotRoutes = require('./routes/autopilot');

app.use('/api/video', videoRoutes);
app.use('/api/policy', policyRoutes);
app.use('/api/thumbnail', thumbnailRoutes);
app.use('/api/seo', seoRoutes);
app.use('/api/autopilot', autopilotRoutes);

// Health check
app.get('/api/health', (req, res) => {
  res.json({
    status: 'ONLINE',
    service: 'YouTube Automation Studio Multi-Agent API',
    version: '1.0.0',
    timestamp: new Date().toISOString()
  });
});

// Full Project Package ZIP Export
app.post('/api/export-bundle', (req, res) => {
  try {
    const { title, srt, seoData, videoFile, thumbnailFile } = req.body;
    const safeName = (title || 'youtube_bundle').replace(/[^a-z0-9_-]/gi, '_');

    res.attachment(`${safeName}.zip`);
    const archive = archiver('zip', { zlib: { level: 9 } });

    archive.on('error', (err) => {
      console.error('Archive error:', err);
      res.status(500).send({ error: err.message });
    });

    archive.pipe(res);

    // 1. Add Subtitles SRT file
    if (srt) {
      archive.append(srt, { name: 'captions.srt' });
    }

    // 2. Add SEO Metadata TXT file (Formatted for YouTube Studio)
    if (seoData) {
      const metadataContent = `=========================================
YOUTUBE STUDIO METADATA PACKAGE
Generated by YouTube Automation Studio AI
=========================================

TITLE:
${seoData.title || ''}

DESCRIPTION:
${seoData.description || ''}

TAGS (Paste into YouTube Studio Tags box):
${seoData.tags || ''}

HASHTAGS:
${(seoData.hashtags || []).join(' ')}
`;
      archive.append(metadataContent, { name: 'youtube_metadata.txt' });
    }

    // 3. Add Video if exists
    if (videoFile) {
      const vPath = path.join(outputsDir, path.basename(videoFile));
      if (fs.existsSync(vPath)) {
        archive.file(vPath, { name: path.basename(vPath) });
      }
    }

    // 4. Add Thumbnail if exists
    if (thumbnailFile) {
      const tPath = path.join(outputsDir, 'thumbnails', path.basename(thumbnailFile));
      if (fs.existsSync(tPath)) {
        archive.file(tPath, { name: path.basename(tPath) });
      }
    }

    archive.finalize();
  } catch (err) {
    res.status(500).json({ success: false, error: err.message });
  }
});

// Serve frontend build
if (fs.existsSync(clientDist)) {
  app.use(express.static(clientDist));
  // Universal fallback for SPA
  app.use((req, res, next) => {
    if (req.method === 'GET' && !req.path.startsWith('/api') && !req.path.startsWith('/uploads') && !req.path.startsWith('/outputs')) {
      return res.sendFile(path.join(clientDist, 'index.html'));
    }
    next();
  });
}

app.listen(PORT, () => {
  console.log(`🚀 YouTube Automation Studio backend listening on port ${PORT}`);
  console.log(`📡 Web UI available at: http://localhost:${PORT}`);
});
